// Localized AI explanation / suggested action for a given incident type,
// falling back to null (caller should then use the raw API text) when the
// type isn't recognized.
export function getIncidentText(lang, type, field, vars) {
  const dict = translations[lang]?.incidentContent?.[type] ?? translations.en.incidentContent?.[type];
  if (!dict) return null;
  let text = dict[field];
  if (text == null) return null;
  if (vars) {
    text = Object.entries(vars).reduce((s, [k, v]) => s.replaceAll(`{${k}}`, v), text);
  }
  return text;
}

// Looks up `path` (dot-separated) in the active language, falling back to
// English, then to `fallback` (default: null) if the key genuinely doesn't
// exist in either — e.g. a dynamic key built from backend data (a check
// type, a status) that this dictionary was never taught about. Callers
// that key off backend-controlled values should always pass an explicit
// `fallback` (usually the raw value) so the UI never shows a raw
// "namespace.key" string to the user.
export function t(lang, path, vars, fallback = null) {
  const parts = path.split(".");
  let node = translations[lang] ?? translations.en;
  for (const p of parts) node = node?.[p];
  if (node == null) {
    // fall back to English if a key is missing in the active language
    node = parts.reduce((acc, p) => acc?.[p], translations.en);
  }
  if (node == null) {
    if (import.meta?.env?.DEV) {
      console.warn(`[i18n] Missing translation for "${path}" — using fallback.`);
    }
    return fallback;
  }
  if (typeof node === "string" && vars) {
    return Object.entries(vars).reduce((s, [k, v]) => s.replaceAll(`{${k}}`, v), node);
  }
  return node;
}
